//! The `Entity` trait (implementer Part C), implemented by `#[derive(Entity)]`
//! (gmclip-macros). Ops are at `(entity, FieldPath)` granularity (SPEC §3.2): a
//! top-level field, or a top-level field plus one map key for fields declared
//! `#[entity(map)]`.

use core::fmt;

use schemars::JsonSchema;
use serde::de::DeserializeOwned;
use serde::{Deserialize, Deserializer, Serialize, Serializer};

use crate::ids::{EntityId, EntityKind, Id, Ulid};
use crate::order::OrderKey;

/// Index of a top-level field in [`Entity::fields`] (declaration order, `id` excluded).
#[derive(Copy, Clone, Eq, Ord, PartialEq, PartialOrd, Hash, Debug)]
pub struct FieldId(pub u16);

/// A top-level field, or a top-level field plus one map key for fields declared
/// `#[entity(map)]` (SPEC §3.2).
#[derive(Clone, Eq, Ord, PartialEq, PartialOrd, Hash, Debug)]
pub struct FieldPath {
    pub field: FieldId,
    pub key: Option<String>,
}

impl FieldPath {
    pub fn field(f: u16) -> Self {
        Self {
            field: FieldId(f),
            key: None,
        }
    }

    pub fn key(f: u16, key: impl Into<String>) -> Self {
        Self {
            field: FieldId(f),
            key: Some(key.into()),
        }
    }

    /// Looks a path up by field name for kind `E` (`None` when the name is unknown, or
    /// a key is given for a non-map field, or no key for a map field).
    pub fn named<E: Entity>(name: &str, key: Option<&str>) -> Option<Self> {
        let d = E::fields().iter().find(|d| d.name == name)?;
        if d.map != key.is_some() {
            return None;
        }
        Some(Self {
            field: d.id,
            key: key.map(str::to_owned),
        })
    }
}

/// A field's value as canonical CBOR bytes (the model's storage form, SPEC §4.4).
/// The empty value means "absent": a map key that is not present (no canonical CBOR
/// item is zero bytes long, so the two never collide).
#[derive(Clone, Eq, PartialEq, Hash, Default)]
pub struct FieldValue(pub Vec<u8>);

impl FieldValue {
    pub const ABSENT: FieldValue = FieldValue(Vec::new());

    pub fn is_absent(&self) -> bool {
        self.0.is_empty()
    }
}

impl fmt::Debug for FieldValue {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        if self.is_absent() {
            return f.write_str("FieldValue(absent)");
        }
        f.write_str("FieldValue(")?;
        for b in self.0.iter().take(32) {
            write!(f, "{b:02x}")?;
        }
        if self.0.len() > 32 {
            write!(f, "…+{}", self.0.len() - 32)?;
        }
        f.write_str(")")
    }
}

impl Serialize for FieldValue {
    fn serialize<S: Serializer>(&self, s: S) -> Result<S::Ok, S::Error> {
        s.serialize_bytes(&self.0)
    }
}

impl<'de> Deserialize<'de> for FieldValue {
    fn deserialize<D: Deserializer<'de>>(d: D) -> Result<Self, D::Error> {
        struct V;
        impl<'de> serde::de::Visitor<'de> for V {
            type Value = FieldValue;
            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("a byte string")
            }
            fn visit_bytes<E: serde::de::Error>(self, v: &[u8]) -> Result<FieldValue, E> {
                Ok(FieldValue(v.to_vec()))
            }
            fn visit_byte_buf<E: serde::de::Error>(self, v: Vec<u8>) -> Result<FieldValue, E> {
                Ok(FieldValue(v))
            }
            fn visit_seq<A: serde::de::SeqAccess<'de>>(
                self,
                mut seq: A,
            ) -> Result<FieldValue, A::Error> {
                let mut out = Vec::new();
                while let Some(b) = seq.next_element::<u8>()? {
                    out.push(b);
                }
                Ok(FieldValue(out))
            }
        }
        d.deserialize_bytes(V)
    }
}

/// Static description of one field, generated by `#[derive(Entity)]`.
#[derive(Copy, Clone, Debug)]
pub struct FieldDesc {
    pub id: FieldId,
    pub name: &'static str,
    /// Declared `#[entity(map)]`: ops address one key at a time.
    pub map: bool,
}

/// One changed field (or map key) found by [`Entity::diff`].
#[derive(Clone, Eq, PartialEq, Debug)]
pub struct FieldChange {
    pub path: FieldPath,
    pub before: FieldValue,
    pub after: FieldValue,
}

/// Errors from model operations. Messages are shape-only: they never carry field
/// values or user text (SPEC §3.12).
#[derive(Clone, Eq, PartialEq, Debug, thiserror::Error)]
pub enum ModelError {
    #[error("unknown field {0:?}")]
    UnknownField(FieldId),
    #[error("field {0} is a map: ops address one key")]
    NeedsKey(&'static str),
    #[error("field {0} is not a map: no key allowed")]
    NoKey(&'static str),
    #[error("map key does not parse")]
    BadKey,
    #[error("field value does not decode: {0}")]
    BadValue(String),
    #[error("unknown entity kind")]
    UnknownKind,
    #[error("entity not found")]
    NotFound,
    #[error("entity already exists")]
    Exists,
    #[error("op does not match the document (before-value or rev mismatch)")]
    Mismatch,
    #[error("transaction rev {got} does not follow document rev {doc}")]
    RevOrder { doc: u64, got: u64 },
    #[error("not implemented yet: {0}")]
    NotImplemented(&'static str),
    #[error("invalid: {0}")]
    Invalid(&'static str),
}

/// An entity kind stored in the document. Implemented by `#[derive(Entity)]`.
pub trait Entity:
    Clone + PartialEq + Serialize + DeserializeOwned + JsonSchema + fmt::Debug + Send + Sync + 'static
{
    const KIND: EntityKind;
    /// Siblings are ordered by an `OrderKey` field.
    const ORDERED: bool;
    fn id(&self) -> Id<Self>;
    fn fields() -> &'static [FieldDesc];
    fn get_field(&self, path: &FieldPath) -> Result<FieldValue, ModelError>;
    fn set_field(&mut self, path: &FieldPath, v: &FieldValue) -> Result<(), ModelError>;
    /// Appends every field (and map key) where `newer` differs from `self`.
    fn diff(&self, newer: &Self, out: &mut Vec<FieldChange>);
    /// The owning entity, if any (drives the children index).
    fn parent(&self) -> Option<EntityId>;
    fn order_key(&self) -> Option<&OrderKey>;

    fn entity_id(&self) -> EntityId {
        EntityId {
            kind: Self::KIND,
            id: self.id().0,
        }
    }
}

/// A field value that names the owning entity (`#[entity(parent)]`).
pub trait AsParent {
    fn as_parent(&self) -> Option<EntityId>;
}

impl<E: Entity> AsParent for Id<E> {
    fn as_parent(&self) -> Option<EntityId> {
        Some(EntityId {
            kind: E::KIND,
            id: self.0,
        })
    }
}

impl<T: AsParent> AsParent for Option<T> {
    fn as_parent(&self) -> Option<EntityId> {
        self.as_ref().and_then(AsParent::as_parent)
    }
}

/// A key of an `#[entity(map)]` field, written as a string in the `FieldPath`.
pub trait MapKey: Ord + Clone {
    fn to_key(&self) -> String;
    fn from_key(s: &str) -> Option<Self>;
}

impl MapKey for String {
    fn to_key(&self) -> String {
        self.clone()
    }
    fn from_key(s: &str) -> Option<Self> {
        Some(s.to_owned())
    }
}

impl MapKey for Ulid {
    fn to_key(&self) -> String {
        self.to_string()
    }
    fn from_key(s: &str) -> Option<Self> {
        // Only the canonical spelling is a key, so one entity never has two keys
        // that parse to the same ULID.
        Ulid::parse(s).ok().filter(|u| u.to_string() == s)
    }
}

impl<E> MapKey for Id<E> {
    fn to_key(&self) -> String {
        self.0.to_string()
    }
    fn from_key(s: &str) -> Option<Self> {
        Ulid::from_key(s).map(Id::new)
    }
}

/// Runtime helpers called by `#[derive(Entity)]`-generated code. Not a stable API.
#[doc(hidden)]
pub mod rt {
    use std::collections::BTreeMap;

    use serde::Serialize;
    use serde::de::DeserializeOwned;

    use super::{FieldChange, FieldId, FieldPath, FieldValue, MapKey, ModelError};
    use crate::cbor;

    pub fn encode<T: Serialize>(v: &T) -> FieldValue {
        FieldValue(cbor::to_vec(v))
    }

    pub fn decode<T: DeserializeOwned>(v: &FieldValue) -> Result<T, ModelError> {
        if v.is_absent() {
            return Err(ModelError::BadValue("absent".into()));
        }
        cbor::from_slice(&v.0)
    }

    pub fn needs_key(name: &'static str) -> ModelError {
        ModelError::NeedsKey(name)
    }

    pub fn no_key(name: &'static str) -> ModelError {
        ModelError::NoKey(name)
    }

    pub fn map_get<K: MapKey, V: Serialize>(
        m: &BTreeMap<K, V>,
        key: &str,
    ) -> Result<FieldValue, ModelError> {
        let k = K::from_key(key).ok_or(ModelError::BadKey)?;
        Ok(m.get(&k).map_or(FieldValue::ABSENT, encode))
    }

    pub fn map_set<K: MapKey, V: DeserializeOwned>(
        m: &mut BTreeMap<K, V>,
        key: &str,
        v: &FieldValue,
    ) -> Result<(), ModelError> {
        let k = K::from_key(key).ok_or(ModelError::BadKey)?;
        if v.is_absent() {
            m.remove(&k);
        } else {
            m.insert(k, decode(v)?);
        }
        Ok(())
    }

    pub fn field_diff<T: Serialize + PartialEq>(
        out: &mut Vec<FieldChange>,
        f: FieldId,
        a: &T,
        b: &T,
    ) {
        if a != b {
            let (before, after) = (encode(a), encode(b));
            // Floats: NaN != NaN, so compare the canonical bytes before recording.
            if before != after {
                out.push(FieldChange {
                    path: FieldPath {
                        field: f,
                        key: None,
                    },
                    before,
                    after,
                });
            }
        }
    }

    pub fn map_diff<K: MapKey, V: Serialize + PartialEq>(
        out: &mut Vec<FieldChange>,
        f: FieldId,
        a: &BTreeMap<K, V>,
        b: &BTreeMap<K, V>,
    ) {
        let mut push = |k: &K, x: Option<&V>, y: Option<&V>| {
            let before = x.map_or(FieldValue::ABSENT, encode);
            let after = y.map_or(FieldValue::ABSENT, encode);
            if before != after {
                out.push(FieldChange {
                    path: FieldPath {
                        field: f,
                        key: Some(k.to_key()),
                    },
                    before,
                    after,
                });
            }
        };
        // Merge-walk both sorted maps.
        let (mut ia, mut ib) = (a.iter().peekable(), b.iter().peekable());
        loop {
            match (ia.peek(), ib.peek()) {
                (None, None) => break,
                (Some((ka, va)), None) => {
                    push(ka, Some(va), None);
                    ia.next();
                }
                (None, Some((kb, vb))) => {
                    push(kb, None, Some(vb));
                    ib.next();
                }
                (Some((ka, va)), Some((kb, vb))) => match ka.cmp(kb) {
                    core::cmp::Ordering::Less => {
                        push(ka, Some(va), None);
                        ia.next();
                    }
                    core::cmp::Ordering::Greater => {
                        push(kb, None, Some(vb));
                        ib.next();
                    }
                    core::cmp::Ordering::Equal => {
                        if va != vb {
                            push(ka, Some(va), Some(vb));
                        }
                        ia.next();
                        ib.next();
                    }
                },
            }
        }
    }
}
