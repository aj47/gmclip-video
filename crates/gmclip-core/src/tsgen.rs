//! TypeScript types for every registry command's arguments and output (backlog A2.01),
//! generated from the same `schemars` JSON Schemas the agent surface publishes, so the
//! UI's types and the schemas cannot drift: `cargo xt gen` writes
//! `app/ui/src/gen/commands.ts`, and `tests/ts_gen.rs` fails while the committed file
//! differs from what the schemas give (the CI check, TS ≡ JSON Schema).
//!
//! No codegen crate: the schemas are plain JSON and this maps the subset schemars emits
//! (`$ref`/`$defs`, objects, arrays, tuples, enums, consts, `anyOf`/`oneOf`/`allOf`,
//! type unions, nullable) onto TypeScript. Shared definitions are emitted once; two
//! different definitions under one name get numbered names.

use std::collections::BTreeMap;

use serde_json::{Map, Value};

use crate::registry::REGISTRY;

/// The generated file's header.
pub const HEADER: &str = "// Generated by `cargo xt gen` from the core command registry's JSON Schemas \
(gmclip-core src/tsgen.rs). Do not edit: change the Rust types and run it again.\n\
// tests/ts_gen.rs fails while this file and the schemas disagree.\n";

fn ident(s: &str) -> String {
    let mut o: String = s
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '_' {
                c
            } else {
                '_'
            }
        })
        .collect();
    if o.is_empty() || o.starts_with(|c: char| c.is_ascii_digit()) {
        o.insert(0, '_');
    }
    o
}

fn key(s: &str) -> String {
    let plain = !s.is_empty()
        && !s.starts_with(|c: char| c.is_ascii_digit())
        && s.chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$');
    if plain {
        s.to_owned()
    } else {
        serde_json::to_string(s).unwrap_or_default()
    }
}

/// Rewrites `$ref`s by `renames` (old def name → new) everywhere in `v`.
fn rename_refs(v: &mut Value, renames: &BTreeMap<String, String>) {
    match v {
        Value::Object(m) => {
            if let Some(Value::String(r)) = m.get_mut("$ref")
                && let Some(name) = r.strip_prefix("#/$defs/")
                && let Some(n) = renames.get(name)
            {
                *r = format!("#/$defs/{n}");
            }
            for x in m.values_mut() {
                rename_refs(x, renames);
            }
        }
        Value::Array(a) => a.iter_mut().for_each(|x| rename_refs(x, renames)),
        _ => {}
    }
}

/// Strips what does not change the type (docs, formats, bounds), so equal types compare
/// equal however they are documented.
fn shape(v: &Value) -> Value {
    match v {
        Value::Object(m) => Value::Object(
            m.iter()
                .filter(|(k, _)| {
                    !matches!(
                        k.as_str(),
                        "description"
                            | "title"
                            | "format"
                            | "minimum"
                            | "maximum"
                            | "default"
                            | "examples"
                            | "minItems"
                            | "maxItems"
                            | "$schema"
                    )
                })
                .map(|(k, x)| (k.clone(), shape(x)))
                .collect(),
        ),
        Value::Array(a) => Value::Array(a.iter().map(shape).collect()),
        other => other.clone(),
    }
}

/// The definitions collected so far, by name.
#[derive(Default)]
struct Defs {
    defs: BTreeMap<String, Value>,
}

impl Defs {
    /// Adds `schema` under `name`; a different shape already there gets a new name.
    /// Returns the name it is known by.
    fn add(&mut self, name: &str, schema: Value) -> String {
        let name = ident(name);
        let mut n = name.clone();
        let mut i = 1;
        loop {
            match self.defs.get(&n) {
                None => {
                    self.defs.insert(n.clone(), schema);
                    return n;
                }
                Some(have) if shape(have) == shape(&schema) => return n,
                Some(_) => {
                    i += 1;
                    n = format!("{name}{i}");
                }
            }
        }
    }

    /// Adds a root schema (with its `$defs`) and returns the root's type name.
    fn add_root(&mut self, fallback: &str, mut root: Value) -> String {
        let defs: Map<String, Value> = root
            .as_object_mut()
            .and_then(|m| m.remove("$defs"))
            .and_then(|d| d.as_object().cloned())
            .unwrap_or_default();
        // a def is named by what it holds: rename those that clash before rewriting refs
        // (repeat until stable: a renamed def may change another def's shape)
        let mut renames: BTreeMap<String, String> = BTreeMap::new();
        for _ in 0..4 {
            let mut changed = false;
            for (k, v) in &defs {
                let mut v = v.clone();
                rename_refs(&mut v, &renames);
                let want = ident(k);
                let mut n = want.clone();
                let mut i = 1;
                while self
                    .defs
                    .get(&n)
                    .is_some_and(|have| shape(have) != shape(&v))
                {
                    i += 1;
                    n = format!("{want}{i}");
                }
                if n != want && renames.get(k) != Some(&n) {
                    renames.insert(k.clone(), n);
                    changed = true;
                }
            }
            if !changed {
                break;
            }
        }
        for (k, v) in defs {
            let mut v = v.clone();
            rename_refs(&mut v, &renames);
            let n = renames.get(&k).cloned().unwrap_or_else(|| ident(&k));
            self.add(&n, v);
        }
        rename_refs(&mut root, &renames);
        let title = root
            .get("title")
            .and_then(Value::as_str)
            .map_or_else(|| fallback.to_owned(), str::to_owned);
        if let Some(m) = root.as_object_mut() {
            m.remove("$schema");
        }
        self.add(&title, root)
    }
}

fn union(parts: Vec<String>) -> String {
    let mut seen: Vec<String> = Vec::new();
    for p in parts {
        if !seen.contains(&p) {
            seen.push(p);
        }
    }
    match seen.len() {
        0 => "never".into(),
        1 => seen.remove(0),
        _ => seen
            .iter()
            .map(|p| {
                if p.contains(" | ") || p.contains(" & ") {
                    format!("({p})")
                } else {
                    p.clone()
                }
            })
            .collect::<Vec<_>>()
            .join(" | "),
    }
}

/// The TypeScript type of a schema.
fn ts(v: &Value, indent: usize) -> String {
    let m = match v {
        Value::Bool(true) => return "unknown".into(),
        Value::Bool(false) => return "never".into(),
        Value::Object(m) => m,
        _ => return "unknown".into(),
    };
    if let Some(Value::String(r)) = m.get("$ref") {
        let name = r
            .strip_prefix("#/$defs/")
            .map_or_else(|| "unknown".into(), ident);
        // a reference with properties beside it (an internally tagged newtype variant:
        // the struct and its tag): both
        return if m.contains_key("properties") {
            let mut rest = m.clone();
            rest.remove("$ref");
            format!("{name} & {}", object(&rest, indent))
        } else {
            name
        };
    }
    if let Some(c) = m.get("const") {
        return serde_json::to_string(c).unwrap_or_default();
    }
    if let Some(Value::Array(e)) = m.get("enum") {
        return union(
            e.iter()
                .map(|x| serde_json::to_string(x).unwrap_or_default())
                .collect(),
        );
    }
    for k in ["anyOf", "oneOf"] {
        if let Some(Value::Array(xs)) = m.get(k) {
            let mut base = m.clone();
            base.remove(k);
            let alts = union(xs.iter().map(|x| ts(x, indent)).collect());
            // a schema with both properties and alternatives: the object & the union
            return if base.contains_key("properties") {
                format!("{} & ({alts})", ts(&Value::Object(base), indent))
            } else {
                alts
            };
        }
    }
    if let Some(Value::Array(xs)) = m.get("allOf") {
        return xs
            .iter()
            .map(|x| ts(x, indent))
            .collect::<Vec<_>>()
            .join(" & ");
    }
    match m.get("type") {
        Some(Value::Array(types)) => union(
            types
                .iter()
                .map(|t| {
                    let mut one = m.clone();
                    one.insert("type".into(), t.clone());
                    ts(&Value::Object(one), indent)
                })
                .collect(),
        ),
        Some(Value::String(t)) => match t.as_str() {
            "string" => "string".into(),
            "integer" | "number" => "number".into(),
            "boolean" => "boolean".into(),
            "null" => "null".into(),
            "array" => {
                if let Some(Value::Array(pre)) = m.get("prefixItems") {
                    format!(
                        "[{}]",
                        pre.iter()
                            .map(|x| ts(x, indent))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                } else {
                    let item = m
                        .get("items")
                        .map_or_else(|| "unknown".into(), |x| ts(x, indent));
                    if item.contains(' ') {
                        format!("Array<{item}>")
                    } else {
                        format!("{item}[]")
                    }
                }
            }
            "object" => object(m, indent),
            _ => "unknown".into(),
        },
        _ if m.contains_key("properties") => object(m, indent),
        _ => "unknown".into(),
    }
}

fn object(m: &Map<String, Value>, indent: usize) -> String {
    let props = m.get("properties").and_then(Value::as_object);
    let extra = match m.get("additionalProperties") {
        None | Some(Value::Bool(false)) => None,
        Some(Value::Bool(true)) => Some("unknown".to_owned()),
        Some(x) => Some(ts(x, indent + 1)),
    };
    let Some(props) = props.filter(|p| !p.is_empty()) else {
        return match extra {
            Some(t) => format!("Record<string, {t}>"),
            None if m.contains_key("additionalProperties") => "Record<string, never>".into(),
            None => "Record<string, unknown>".into(),
        };
    };
    let required: Vec<&str> = m
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let pad = "  ".repeat(indent + 1);
    let mut out = String::from("{\n");
    for (k, v) in props {
        let opt = if required.contains(&k.as_str()) {
            ""
        } else {
            "?"
        };
        if let Some(d) = v.get("description").and_then(Value::as_str) {
            let d = d.replace("*/", "* /");
            out.push_str(&format!(
                "{pad}/** {} */\n",
                d.lines().collect::<Vec<_>>().join(" ")
            ));
        }
        out.push_str(&format!("{pad}{}{opt}: {};\n", key(k), ts(v, indent + 1)));
    }
    if let Some(t) = extra {
        out.push_str(&format!("{pad}[key: string]: unknown; // values: {t}\n"));
    }
    out.push_str(&"  ".repeat(indent));
    out.push('}');
    out
}

/// The TypeScript module for the whole registry: every type once, then `Commands`
/// mapping each command name to its `args` and `output`.
pub fn commands_ts() -> String {
    commands_ts_from(REGISTRY.iter().map(|c| {
        let m = c.meta();
        (
            m.name,
            serde_json::to_value((m.args_schema)()).unwrap_or(Value::Null),
            serde_json::to_value((m.output_schema)()).unwrap_or(Value::Null),
        )
    }))
}

/// [`commands_ts`] over given `(name, args schema, output schema)`.
pub fn commands_ts_from(
    commands: impl IntoIterator<Item = (&'static str, Value, Value)>,
) -> String {
    let mut defs = Defs::default();
    let mut table: Vec<(&str, String, String)> = Vec::new();
    for (name, args, out) in commands {
        let a = defs.add_root(&format!("{}_args", ident(name)), args);
        let o = defs.add_root(&format!("{}_output", ident(name)), out);
        table.push((name, a, o));
    }
    let mut s = emit(HEADER, &defs);
    s.push_str("/** Every registry command: its arguments and its output. */\nexport interface Commands {\n");
    for (name, a, o) in &table {
        s.push_str(&format!("  {}: {{ args: {a}; output: {o} }};\n", key(name)));
    }
    s.push_str("}\n\nexport type CommandName = keyof Commands;\n");
    s
}

/// The header, then every definition once, each an `export type`.
fn emit(header: &str, defs: &Defs) -> String {
    let mut s = String::from(header);
    s.push('\n');
    for (name, schema) in &defs.defs {
        if let Some(d) = schema.get("description").and_then(Value::as_str) {
            let d = d.replace("*/", "* /");
            s.push_str(&format!(
                "/** {} */\n",
                d.lines().collect::<Vec<_>>().join(" ")
            ));
        }
        s.push_str(&format!("export type {name} = {};\n\n", ts(schema, 0)));
    }
    s
}

/// A TypeScript module of the given root schemas (each named by its `title`, else by its
/// given name), every definition once, as for the commands: the app's UI event payloads
/// use it (`app/ui/src/gen/events.ts`). Returns the module and each root's type name, in
/// order, for the caller to add what ties them together.
pub fn module_ts(
    header: &str,
    roots: impl IntoIterator<Item = (String, Value)>,
) -> (String, Vec<String>) {
    let mut defs = Defs::default();
    let names: Vec<String> = roots
        .into_iter()
        .map(|(name, schema)| defs.add_root(&name, schema))
        .collect();
    (emit(header, &defs), names)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn maps_the_schema_shapes_schemars_emits() {
        let args = json!({
            "title": "XArgs", "type": "object", "required": ["cut", "kind"],
            "properties": {
                "cut": {"type": "string", "description": "The cut."},
                "kind": {"$ref": "#/$defs/Kind"},
                "n": {"type": ["integer", "null"]},
                "pair": {"type": "array", "prefixItems": [{"type": "number"}, {"type": "number"}]},
                "tags": {"type": "array", "items": {"type": "string"}},
                "m": {"type": "object", "additionalProperties": {"type": "number"}},
                "e": {"oneOf": [{"type": "string", "const": "drop"}, {"type": "object", "required": ["text"], "properties": {"text": {"type": "string"}}}]}
            },
            "$defs": {"Kind": {"type": "string", "enum": ["pauses", "fillers"]}}
        });
        let ts = commands_ts_from([("x_do", args, json!({"title": "Done", "type": "object"}))]);
        assert!(
            ts.contains("export type Kind = \"pauses\" | \"fillers\";"),
            "{ts}"
        );
        assert!(ts.contains("  cut: string;"), "{ts}");
        assert!(ts.contains("/** The cut. */"), "{ts}");
        assert!(ts.contains("  kind: Kind;"), "{ts}");
        assert!(ts.contains("  n?: number | null;"), "{ts}");
        assert!(ts.contains("  pair?: [number, number];"), "{ts}");
        assert!(ts.contains("  tags?: string[];"), "{ts}");
        assert!(ts.contains("  m?: Record<string, number>;"), "{ts}");
        assert!(ts.contains("  e?: \"drop\" | {"), "{ts}");
        assert!(
            ts.contains("  x_do: { args: XArgs; output: Done };"),
            "{ts}"
        );
    }

    #[test]
    fn a_reference_with_a_tag_beside_it_keeps_both() {
        let ev = json!({"title": "Ev", "oneOf": [
            {"$ref": "#/$defs/Progress", "type": "object", "required": ["kind"],
             "properties": {"kind": {"type": "string", "const": "analysis"}}},
            {"type": "object", "required": ["kind"], "properties": {"kind": {"type": "string", "const": "changed"}}}
        ], "$defs": {"Progress": {"type": "object", "required": ["done"], "properties": {"done": {"type": "number"}}}}});
        let (ts, names) = module_ts("// h\n", [("Ev".to_owned(), ev)]);
        assert_eq!(names, ["Ev"]);
        assert!(
            ts.contains("export type Ev = (Progress & {\n  kind: \"analysis\";\n}) | {"),
            "{ts}"
        );
        assert!(
            ts.contains("export type Progress = {\n  done: number;\n};"),
            "{ts}"
        );
    }

    #[test]
    fn a_changed_field_changes_the_file_and_clashes_get_their_own_names() {
        let a = |t: &str| json!({"title": "A", "type": "object", "required": ["f"], "properties": {"f": {"type": t}}});
        let one =
            commands_ts_from([("c", a("string"), json!({"title": "Done", "type": "object"}))]);
        let two = commands_ts_from([(
            "c",
            a("integer"),
            json!({"title": "Done", "type": "object"}),
        )]);
        assert_ne!(
            one, two,
            "a schema field change shows in the generated file"
        );
        let both = commands_ts_from([
            ("c", a("string"), json!({"title": "Done", "type": "object"})),
            (
                "d",
                a("integer"),
                json!({"title": "Done", "type": "object"}),
            ),
        ]);
        assert!(
            both.contains("export type A = {") && both.contains("export type A2 = {"),
            "{both}"
        );
        assert!(both.contains("d: { args: A2; output: Done }"), "{both}");
    }
}
