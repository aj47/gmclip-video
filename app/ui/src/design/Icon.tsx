export type IconName = keyof typeof P;

/** An icon, decorative by default (the control around it carries the name). */
export function Icon(props: { name: IconName | string; size?: number; class?: string; label?: string }) {
  const draw = () => (P[props.name] ?? P.dot!)();
  return (
    <svg
      class={`icon${props.class ? ` ${props.class}` : ""}`}
      width={props.size ?? 16}
      height={props.size ?? 16}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      stroke-width="2"
      stroke-linecap="round"
      stroke-linejoin="round"
      aria-hidden={props.label ? undefined : "true"}
      role={props.label ? "img" : undefined}
      aria-label={props.label}
      data-icon={props.name}
    >
      {draw()}
    </svg>
  );
}
